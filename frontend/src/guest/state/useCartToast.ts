import { useEffect, useState } from 'react';

/**
 * СКОЛЬКО ДЕРЖИМ ПОЛОСУ «ДОБАВЛЕНО».
 *
 * Четыре секунды. Короче — не успеть прочитать три слова и дотянуться пальцем
 * до кнопки: на телефоне полоса внизу, и путь от «увидел» до «нажал» это
 * полсекунды глазами плюс движение руки. Дольше — она перестаёт читаться как
 * ответ на действие и снова превращается в мебель, ровно в то, от чего ушли;
 * а при добавлении нескольких блюд подряд просто не успевала бы исчезать.
 *
 * Короткий срок здесь допустим только потому, что полоса — НЕ единственный
 * вход в корзину: иконка в шапке видна всегда. Будь она единственной, четырёх
 * секунд было бы мало по-человечески (и по WCAG 2.2.1, где у исчезающего
 * управления должен быть либо большой запас, либо другой путь). Другой путь
 * есть, и он постоянный.
 */
export const CART_TOAST_MS = 4000;

/**
 * `true` в течение нескольких секунд после каждого добавления.
 *
 * Ведём по СЧЁТЧИКУ добавлений, а не по «в корзине что-то есть»: второе
 * означает «висеть всегда», и именно так полоса и жила. Счётчик растёт и при
 * повторном добавлении того же блюда — значит полоса покажется снова, а не
 * промолчит, потому что состав корзины «не изменился».
 */
export function useCartToast(ticks: number, ms: number = CART_TOAST_MS): boolean {
  const [visible, setVisible] = useState(false);

  useEffect(() => {
    // Нулевой тик — это открытие экрана, а не добавление: после перезагрузки
    // страницы полоса всплывать не должна.
    if (ticks === 0) return;
    setVisible(true);
    const timer = window.setTimeout(() => setVisible(false), ms);
    return () => window.clearTimeout(timer);
  }, [ticks, ms]);

  return visible;
}

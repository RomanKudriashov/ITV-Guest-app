import { cmsPath } from '@/app/hostRole';
import type { StaffUser } from '@/api/types';

/**
 * КУДА ЧЕЛОВЕК ПОПАДАЕТ ПОСЛЕ ВХОДА — одно правило на все поверхности.
 *
 * Раньше посадка была одна на всех: `/dashboard`. Для повара это раздел, куда
 * ему нельзя, и он видел отказ с кнопкой «на трекер». Отказ мы сделали
 * аккуратно, а посадку не поправили — человек каждый раз проходил через
 * запертую дверь, чтобы попасть к себе.
 *
 * РЕШАЕМ ПО ПРАВАМ, А НЕ ПО НАЗВАНИЮ РОЛИ. `has_cms_access` — то же поле, по
 * которому пускает бэкенд; «управляющий» и «админ» это его следствия, а не
 * причина. Заводя завтра четвёртую роль, посадку править не придётся.
 *
 * Три исхода, и третий не выдуман: сотрудник без единой привязки существует —
 * его завели и ещё не назначили. Ему нужен трекер, который скажет об этом
 * прямо, а не CMS, которая скажет «нельзя».
 */
export function homePathFor(user: StaffUser | null): string {
  if (user?.has_cms_access) return cmsPath('/dashboard');
  return '/tracker';
}

/**
 * Можно ли вести человека по сохранённому адресу (закладка, ссылка, возврат
 * после входа).
 *
 * Уважать `from` надо: человек шёл к конкретному экрану. Но вести его туда,
 * где он получит отказ, — значит повторять ту же ошибку, только по его
 * собственной закладке. Поэтому адрес CMS без права на CMS отбрасывается, и
 * человек идёт к себе.
 */
export function landingPath(user: StaffUser | null, from: string | null | undefined): string {
  const home = homePathFor(user);
  if (!from) return home;

  const cmsRoot = cmsPath('');
  const intoCms = from === cmsRoot || from.startsWith(`${cmsRoot}/`);
  if (intoCms && !user?.has_cms_access) return home;
  return from;
}

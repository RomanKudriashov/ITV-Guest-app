/**
 * ЗАКРЫТЬ СОКЕТ, КОТОРЫЙ ЕЩЁ НЕ ОТКРЫЛСЯ, — ТИХО.
 *
 * `close()` на сокете в состоянии CONNECTING браузер исполняет, но пишет в
 * консоль «WebSocket is closed before the connection is established». Так
 * бывает при каждом быстром уходе с экрана и при двойном запуске эффекта в
 * режиме разработки. Внешний аудит (E2E-003) принял это предупреждение за
 * неработающий сокет — на стенде он работает, шумела наша же уборка.
 *
 * Не открывшийся сокет закрываем в момент открытия: уборка та же, без шума.
 * Остальные обработчики вызывающий уже снял — данные после ухода не придут.
 */
export function closeSocket(socket: WebSocket): void {
  if (socket.readyState === WebSocket.CONNECTING) {
    socket.onopen = () => socket.close();
    return;
  }
  socket.close();
}

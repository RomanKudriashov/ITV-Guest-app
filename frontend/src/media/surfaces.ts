/**
 * РЕЕСТР КАДРОВ: где картинка появится у гостя и в каком соотношении.
 *
 * Одно место на всё приложение. Поменяется вёрстка витрины — правится здесь, а
 * не в шести редакторах, каждый из которых иначе обзаведётся своим мнением о
 * том, какой формы кадр.
 *
 * ЦИФРЫ ИЗМЕРЕНЫ, А НЕ ВЗЯТЫ НА ГЛАЗ. Поверхности гостя заданы фиксированной
 * высотой при резиновой ширине, поэтому соотношение зависит от ширины экрана и
 * из кода не читается. Мерялось на живом стенде (`e2e/measure-ratios.mjs`) на
 * двух ширинах: 390 (телефон) и 1440 (десктоп).
 *
 * ГЛАВНОЕ СЛЕДСТВИЕ ИЗМЕРЕНИЙ. У шапки отеля кадр расходится больше чем вдвое:
 * 1.55 на телефоне против 3.55 на десктопе. Одним кадром это не закрыть —
 * что бы человек ни обрезал, один из двух гостей увидит другое. Поэтому у
 * поверхности есть ВТОРОЕ соотношение (`alsoSeenAs`): рамку человек ставит под
 * телефон, а редактор подсвечивает, что от неё уцелеет на широком экране.
 * Догадываться по цвету не нужно — подпись говорит это словами.
 */

export interface Surface {
  /** Соотношение рамки: ширина / высота. */
  ratio: number;
  /**
   * Второе соотношение, в котором ту же картинку покажут на другой ширине.
   * Отсутствует — кадр везде одинаковый, подсвечивать нечего.
   */
  alsoSeenAs?: number;
  /** Ключ i18n с объяснением: где именно это увидит гость. */
  whereKey: string;
}

/**
 * Ключи — РОЛИ, а не экраны: одна и та же картинка позиции показывается и
 * карточкой, и в списке, но кадр у неё один, и роль у неё одна.
 */
export const SURFACES = {
  /** Шапка витрины: имя отеля, часы, погода поверх кадра. */
  hotelCover: { ratio: 390 / 252, alsoSeenAs: 1080 / 304, whereKey: 'media.where.hotelCover' },
  /** Плитка заведения/раздела на главной. */
  homeTile: { ratio: 358 / 266, alsoSeenAs: 509 / 314, whereKey: 'media.where.homeTile' },
  /** Кадр в шапке раздела каталога. */
  categoryCover: { ratio: 390 / 252, alsoSeenAs: 1080 / 304, whereKey: 'media.where.categoryCover' },
  /** Фото заведения: плитка в списке и шапка внутри. */
  venue: { ratio: 358 / 266, alsoSeenAs: 509 / 314, whereKey: 'media.where.venue' },
  /** Карточка блюда: главный кадр позиции. */
  item: { ratio: 390 / 224, alsoSeenAs: 560 / 268, whereKey: 'media.where.item' },
  /**
   * Логотип. Своё соотношение и своя логика: логотипы бывают и квадратные, и
   * вытянутые, и резать их рамкой значило бы портить знак. Здесь кадр —
   * способ убрать поля вокруг, а не вписать в формат, поэтому 1:1 и
   * `contain`-превью в шапке.
   */
  logo: { ratio: 1, whereKey: 'media.where.logo' },
  /**
   * Фон витрины. Виден целиком за всеми поверхностями, на телефоне —
   * вертикально. Второй кадр — десктопный.
   */
  background: { ratio: 390 / 844, alsoSeenAs: 1440 / 900, whereKey: 'media.where.background' },
} as const satisfies Record<string, Surface>;

export type SurfaceKey = keyof typeof SURFACES;

/**
 * Доля ШИРИНЫ рамки, которая уцелеет на второй ширине экрана.
 *
 * Считаем по правилу `object-fit: cover`: кадр с соотношением `ratio`,
 * показанный в окне с соотношением `other`, обрезается по той оси, где он
 * «шире» окна. Если второе окно ШИРЕ (3.55 против 1.55) — режется верх и низ,
 * ширина цела; если уже — режутся бока.
 *
 * Возвращаем обе доли: редактор рисует по ним рамку внутри рамки.
 */
export function safeArea(surface: Surface): { width: number; height: number } | null {
  if (!surface.alsoSeenAs) return null;
  const other = surface.alsoSeenAs;
  if (other > surface.ratio) {
    // Второе окно шире: сверху и снизу отрежут.
    return { width: 1, height: surface.ratio / other };
  }
  // Второе окно уже: отрежут по бокам.
  return { width: other / surface.ratio, height: 1 };
}

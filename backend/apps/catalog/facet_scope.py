"""
КОМУ КАКОЙ СПРАВОЧНИК ПРИМЕНИМ.

Массаж не содержит глютена. Трансфер не бывает халяльным. Тем не менее карточка
позиции показывала аллергены и диетические маркеры любому типу заведения —
пустыми полями, которые сотрудник спа честно пытался заполнить, а потом
переставал верить экрану вообще.

ДВА УРОВНЯ, И ОБА НУЖНЫ.

  1. СПРАВОЧНИК ЦЕЛИКОМ. «Аллергены бывают у съедобного» — это свойство самого
     справочника, а не отеля: оно одинаково у всех и не настраивается. Живёт
     здесь, таблицей.
  2. ЗАПИСЬ ВНУТРИ. «Халяль» осмыслен и у блюда, и у товара; «содержит орехи» —
     только у блюда. Отель вправе сузить область записи, и это хранится полем
     `applies_to` рядом с записью.

Сузить — можно, расширить сверх справочника — нет: аллерген, объявленный
применимым к странице, не стал бы от этого осмысленным, зато сломал бы обещание
уровня 1. Поэтому область записи ПЕРЕСЕКАЕТСЯ с областью справочника, а не
заменяет её.

СУЖЕНИЕ НЕ СТИРАЕТ ДАННЫХ. Связь позиции со значением остаётся в базе; она лишь
перестаёт показываться. Вернули применимость — всё на месте. Иначе отель,
попробовавший настройку, терял бы проставленное руками, а «попробовать» — это
ровно то, что делают в первый день.

ОДНО ПРАВИЛО НА ПАНЕЛЬ И ВИТРИНУ. Функции ниже зовут и CMS, и гостевая выдача.
Второй экземпляр этого правила разошёлся бы с первым, и отель увидел бы у себя
одно, а гость — другое; спорить в этот момент было бы не о чем, потому что оба
экрана «правы».
"""

from __future__ import annotations

from apps.catalog.nouns import OfferingNoun


class FacetKind:
    """Справочники, у которых есть область применения."""

    ALLERGENS = "allergens"
    MARKERS = "markers"


# Справочник → слова, при которых он вообще осмыслен.
#
# Аллергены и маркеры — про съедобное и про то, что кладут в рот: блюдо и товар
# (орешки из минибара). Услуга, страница и нейтральная позиция сюда не входят —
# не потому, что «пока не настроили», а потому, что вопрос не имеет смысла.
KIND_SCOPE: dict[str, frozenset[str]] = {
    FacetKind.ALLERGENS: frozenset({OfferingNoun.DISH, OfferingNoun.GOODS}),
    FacetKind.MARKERS: frozenset({OfferingNoun.DISH, OfferingNoun.GOODS}),
}


def kind_scope(kind: str) -> frozenset[str]:
    """
    Область справочника. Незнакомый справочник применим везде.

    Умолчание широкое намеренно: новый справочник, про который здесь ещё не
    написали строку, должен вести себя как раньше — показываться, — а не
    исчезнуть молча со всех карточек.
    """
    return KIND_SCOPE.get(kind, frozenset(OfferingNoun.values))


def entry_scope(kind: str, applies_to) -> frozenset[str]:
    """
    Область одной записи: сужение отеля, пересечённое с областью справочника.

    Пусто — «как у справочника». Именно пусто, а не «нигде»: запись, у которой
    отель ничего не трогал, обязана вести себя как весь справочник.
    """
    allowed = kind_scope(kind)
    narrowed = {str(value) for value in (applies_to or [])}
    if not narrowed:
        return allowed
    return frozenset(narrowed) & allowed


def applies(kind: str, applies_to, noun: str) -> bool:
    """Показывать ли эту запись позиции с таким словом."""
    return noun in entry_scope(kind, applies_to)


def kind_applies(kind: str, noun: str) -> bool:
    """
    Показывать ли ВЕСЬ справочник позиции с таким словом.

    Ответ «нет» означает, что в карточке раздела нет вовсе — ни заголовка, ни
    пустого списка. Серое поле сказало бы «сюда можно, но не сейчас», а правда
    другая: сюда нельзя никогда, и место занимать незачем.
    """
    return noun in kind_scope(kind)

"""
КАК НАЗЫВАЕТСЯ ТО, ЧТО ЛЕЖИТ В КАТАЛОГЕ ЗАВЕДЕНИЯ.

«Добавить блюдо» на экране спа — это не мелочь стиля. Сотрудник спа читает
кнопку буквально, ищет глазами что-то съедобное и на секунду теряет уверенность,
что он вообще там, где нужно. Двенадцать типов заведений, а слово было одно на
всех — ресторанное.

СЛОВО ВЫВОДИТСЯ ИЗ ТИПА ЗАВЕДЕНИЯ, А НЕ ХРАНИТСЯ ПОЛЕМ. Второе поле про то же
самое разошлось бы с типом на первом же переименовании сервиса: тип поменяли,
слово осталось прежним, и никто этого не заметил бы до жалобы. Это тот же
довод, по которому выводится тип трекера и вид гостевой карточки
(`apps/orders/services/tracker_types.py`), и карта здесь устроена так же —
одной таблицей, а не условиями по коду.

ЧТО ИМЕННО ЖИВЁТ ЗДЕСЬ, А ЧТО НЕТ. Здесь — только КОД существительного:
`dish`, `service`, `goods`, `page`, `item`. Самих слов здесь нет и быть не
может: «блюдо» среднего рода, «услуга» женского, «товар» мужского, и русские
фразы вокруг них согласуются по-разному — «Новое блюдо», но «Новая услуга» и
«Новый товар». Склеивать фразу из кусков нельзя ни на одном языке с родом и
падежами, поэтому фразы целиком лежат в переводах фронта, а сюда приходит код,
по которому фронт выбирает нужный набор.

ПОЧЕМУ НА СЕРВЕРЕ, А НЕ ТОЛЬКО НА ФРОНТЕ. Вход у карты один — `Service.Type`, и
он живёт здесь. Держать карту там, где её читают, значило бы завести её дважды
(панель и витрина) и однажды разойтись. Фронт получает готовый код в ответе о
заведении и повторяет карту у себя только как близнеца, который сверяется
тестом.
"""

from __future__ import annotations

from django.db import models


class OfferingNoun(models.TextChoices):
    """
    Чем заведение наполняет каталог — словом, которое человек ожидает увидеть.

    Пять, а не двенадцать: слово отвечает на вопрос «что это за штука», и
    ресторан с баром отвечают на него одинаково. Дробить дальше значило бы
    заводить синонимы, которые ничего не различают.
    """

    DISH = "dish", "Блюдо"
    SERVICE = "service", "Услуга"
    GOODS = "goods", "Товар"
    PAGE = "page", "Страница"
    ITEM = "item", "Позиция"


# Тип заведения (hotels.Service.Type) → слово. Ключи те же, что у карт трекера и
# гостевой карточки: добавили тип — добавили строку во все три, иначе сторож
# полноты покажет пропуск.
SERVICE_TYPE_TO_NOUN: dict[str, str] = {
    # Еда и напитки: человек за этим экраном думает блюдами.
    "restaurant": OfferingNoun.DISH,
    "bar": OfferingNoun.DISH,
    "room_service": OfferingNoun.DISH,
    # Мини-бар и магазин — ОДИН тип, и товар покрывает оба его смысла: орешки
    # из минибара товар ровно так же, как сувенир с витрины. Обратное неверно —
    # сувенир блюдом не назовёшь, — поэтому из двух слов выбрано это. Делить
    # тип надвое ради слова не стали: это правка модели, задевающая живые отели.
    "minibar": OfferingNoun.GOODS,
    # Работа, а не вещь: её оказывают.
    "spa": OfferingNoun.SERVICE,
    "pool": OfferingNoun.SERVICE,
    "transfer": OfferingNoun.SERVICE,
    "concierge": OfferingNoun.SERVICE,
    "excursions": OfferingNoun.SERVICE,
    "housekeeping": OfferingNoun.SERVICE,
    # Единственный тип, который не создаёт заказа вовсе: гость это ЧИТАЕТ.
    # «Раздел» занят категориями каталога, поэтому страница.
    "info": OfferingNoun.PAGE,
    # «Свой» — заведение, про которое система не знает ничего заранее. Честное
    # общее слово лучше догадки: назвать содержимое блюдом наугад значит
    # ошибиться у всех, кто завёл этот тип именно потому, что не подошли
    # остальные.
    "custom": OfferingNoun.ITEM,
}


def noun_for_service_type(service_type: str) -> str:
    """
    Слово для типа заведения. Неизвестный тип — нейтральная «позиция».

    Умолчание намеренно то же, что у «Своего»: незнакомый тип означает ровно
    то же самое — мы не знаем, что там лежит, и врать словом не будем.
    """
    return SERVICE_TYPE_TO_NOUN.get(service_type, OfferingNoun.ITEM)


def noun_for_service(service) -> str:
    """Слово для заведения; `None` вместо заведения — «позиция»."""
    if service is None:
        return OfferingNoun.ITEM
    return noun_for_service_type(service.type)

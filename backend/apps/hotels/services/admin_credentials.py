"""
Пароль администратора отеля уходит ЕМУ, а не оператору платформы.

Раньше `POST /hotels/{id}/admins` возвращала новый пароль в теле ответа. Это
не «неудобно», а готовый захват тенанта: любой, кто дотянулся до платформенной
консоли, получал полный доступ в CMS любого отеля — меню, цены, гостей,
заказы, переписки. Причём бесследно для отеля: тот не узнавал, что его пароль
кто-то сбросил и прочитал.

Теперь оператор видит только адрес, на который ушло письмо.

ГЛАВНОЕ ПРАВИЛО: ПАРОЛЬ НЕ ПРИМЕНЯЕТСЯ, ЕСЛИ ПИСЬМО НЕ УШЛО. Отправка идёт
ВНУТРИ транзакции, которая меняет пароль; отказ почты роняет транзакцию, и в
базе остаётся прежний пароль. Иначе получилась бы худшая из картин: оператору
сказали «отправлено», админу не пришло ничего, а войти больше нельзя ни тому,
ни другому.

Обратная сторона этого выбора названа честно: письмо уходит до коммита, и
если коммит потом упадёт, админ получит пароль, которого нет в базе. Это
чинится повторным сбросом и не запирает никого — в отличие от обратного
порядка.

ПОЧЕМУ ОТКАЗ, А НЕ ОЧЕРЕДЬ. Очередь означала бы ответ «готово» в момент, когда
про доставку ещё ничего не известно, — то есть ровно то, что здесь
запрещено. Повтор внутри запроса не меняет исхода при по-настоящему мёртвом
SMTP, зато держит оператора на таймауте. Отказ виден сразу и чинится сразу.

ПОЧЕМУ КОНСОЛЬНЫЙ BACKEND СЧИТАЕТСЯ «ПОЧТЫ НЕТ». `console` печатает письмо в
stdout, а `dummy` молча его выбрасывает. Оба возвращают «успех». С консольным
мы бы отчитались об отправке и положили пароль в `docker compose logs` —
то есть ровно туда, откуда его и убирали. Поэтому такие backend'ы — это
«почта не настроена», и операция отказывает.
"""

from __future__ import annotations

import logging

from django.conf import settings
from django.core.mail import EmailMessage
from django.utils import timezone

from apps.core.errors import DomainError

logger = logging.getLogger(__name__)

# Backend'ы, которые не доставляют письмо, но рапортуют об успехе.
# `locmem` в этот список НЕ входит: он копит письма в `mail.outbox`, и именно
# на нём тесты проверяют, что письмо ушло и по какому адресу.
_NON_DELIVERING = (
    "django.core.mail.backends.console.EmailBackend",
    "django.core.mail.backends.dummy.EmailBackend",
)

_SUBJECT = "Доступ в панель управления отелем"

_BODY = """\
Здравствуйте!

Для вашего отеля «{hotel}» {action}.

Адрес входа: {url}
Логин: {email}
Пароль: {password}

Смените пароль после первого входа.

Это письмо отправлено автоматически, отвечать на него не нужно.
"""


class MailNotConfigured(DomainError):
    """Почта не настроена — отправлять пароль некуда."""

    status = 503
    code = "mail_not_configured"


class MailNotSent(DomainError):
    """Почта настроена, но письмо не ушло."""

    status = 502
    code = "mail_not_sent"


def mail_is_deliverable() -> bool:
    """Умеет ли текущая настройка ДОСТАВИТЬ письмо, а не изобразить доставку."""
    return getattr(settings, "EMAIL_BACKEND", "") not in _NON_DELIVERING


def send_admin_password(hotel, *, email: str, password: str, is_new: bool) -> dict:
    """
    Отправить пароль администратору отеля.

    Возвращает то, что МОЖНО показать оператору: адрес и момент отправки.
    Пароля в возвращаемом словаре нет и быть не должно — это единственная
    причина, по которой функция вообще возвращает что-то, а не None.

    Бросает исключение при любой неудаче: вызывающий обязан откатить смену
    пароля, а не сообщить об успехе.
    """
    if not mail_is_deliverable():
        raise MailNotConfigured(
            "Почта не настроена: пароль администратору отправить нечем. "
            "Задайте EMAIL_BACKEND и параметры SMTP.",
            code="mail_not_configured",
        )

    body = _BODY.format(
        # `name` переводимое: подставить его как есть значит написать
        # администратору «Для вашего отеля «{'ru': 'Кристалл'}»».
        hotel=hotel.name_i18n,
        action="заведён администратор" if is_new else "сброшен пароль администратора",
        # Адрес панели отеля. `/login` остаётся постоянным редиректом сюда
        # же — письма трёхлетней давности обязаны открываться.
        url=hotel.public_guest_url("/admin"),
        email=email,
        password=password,
    )
    message = EmailMessage(
        subject=_SUBJECT,
        body=body,
        from_email=settings.DEFAULT_FROM_EMAIL,
        to=[email],
    )
    try:
        sent = message.send(fail_silently=False)
    except Exception as exc:  # noqa: BLE001 — сеть, SMTP, что угодно: исход один
        # В лог — БЕЗ тела письма: там пароль. Причина отказа этого не требует.
        logger.warning("пароль администратора отеля %s не отправлен: %s", hotel.subdomain, exc)
        raise MailNotSent(
            "Письмо с паролем не ушло — пароль не изменён. Повторите позже.",
            code="mail_not_sent",
        ) from exc

    if not sent:
        logger.warning("пароль администратора отеля %s: SMTP не принял письмо", hotel.subdomain)
        raise MailNotSent(
            "Почтовый сервер не принял письмо — пароль не изменён.",
            code="mail_not_sent",
        )

    return {"delivered_to": email, "sent_at": timezone.now().isoformat()}

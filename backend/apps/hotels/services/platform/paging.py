"""
Пределы выдач платформенной консоли.

ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Семь выдач консоли возвращали всё, что нашлось.
На трёх отелях это незаметно, на двухстах — уже нет: список отелей отдавал
212 записей и 1064 запроса. Предел, размазанный по семи местам разными
числами, через полгода станет семью разными пределами, поэтому он один и
здесь.

ЧЕСТНЫЙ ОТВЕТ ВАЖНЕЕ ПРЕДЕЛА. Молча обрезанный список — худшее из решений:
оператор видит двадцать пять узлов и уверен, что их двадцать пять. Поэтому
выдача всегда несёт `total`: сколько есть на самом деле.
"""

from __future__ import annotations

from typing import Any

DEFAULT_LIMIT = 100
MAX_LIMIT = 500


def clamp(limit: int | None, *, default: int = DEFAULT_LIMIT, maximum: int = MAX_LIMIT) -> int:
    """Предел из запроса — в разумные рамки. Ноль и минус означают «по умолчанию»."""
    if not limit or limit < 1:
        return default
    return min(limit, maximum)


def envelope(rows: list[Any], total: int, limit: int) -> dict[str, Any]:
    """
    Выдача с честным хвостом.

    `truncated` — не украшение: по нему интерфейс говорит «показаны первые N
    из M», а не делает вид, что показал всё.
    """
    return {
        "items": rows,
        "total": total,
        "limit": limit,
        "truncated": total > len(rows),
    }

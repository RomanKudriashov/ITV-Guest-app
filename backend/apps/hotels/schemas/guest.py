"""
Схемы отеля, видимые гостю.

Схемы объявлены ЗДЕСЬ, а не рядом со вьюхой: схема — это контракт домена, и
жить она должна там же, где модель и сервис, которые его исполняют. Пока
объявления лежали во вьюхах, один и тот же ресурс описывался в трёх местах, а
общее уезжало в общий `api/schemas.py`, куда сваливалось всё подряд.

Раскладка по ПОТРЕБИТЕЛЮ (guest / cms / platform / staff): у одного ресурса
разные права и разные поля наружу, и складывать их в один файл значит однажды
отдать гостю поле, которое собирали для оператора.
"""

from __future__ import annotations

from typing import Any

from ninja import Schema



class HotelOut(Schema):
    id: str
    name: str
    subdomain: str
    currency: str
    currency_minor_units: int
    timezone: str
    default_language: str
    languages: list[dict[str, Any]]
    theme: dict[str, Any]
    # Обложка отеля для парадной главной (R5). Поле обязано быть В СХЕМЕ:
    # ninja отдаёт ровно то, что она описывает, и не объявленный ключ он
    # выбрасывает молча — сервер отдавал обложку, а гость её не получал.
    cover_image: str | None = None
    # Включён ли модуль «Управление номером». Ровно тот же случай, что и с
    # обложкой строкой выше: без объявления в схеме ninja выбросит ключ молча,
    # и гостевой фронт останется слеп к модулю, как был до G5.
    room_control_enabled: bool = False

"""
Фоновые операции платформы.

ПЕРВАЯ ТАКАЯ В ПРОЕКТЕ. До неё вся длительная работа была привязана к одному
отелю (команда оборудованию, рассылка уведомления) и укладывалась в секунды.
Публикация — другой род: она идёт по всем отелям цели, каждый в своём
тенант-контексте, и её нельзя ни выполнить в запросе, ни считать неделимой.

ПОЧЕМУ БЕЗ РЕТРАЕВ ЗАДАЧИ ЦЕЛИКОМ. Повтор всей публикации безопасен по
устройству (идемпотентна и возобновляема), но автоматический ретрай прятал бы
причину: упавшая задача обязана оставить след в отчёте, а не тихо перезапуститься
до тех пор, пока не совпадёт. `CELERY_TASK_ACKS_LATE` при этом включён, и убитый
воркер вернёт сообщение в очередь — тогда задача продолжит с того отеля, на
котором её прервали: сделанные записаны в отчёте.
"""

from __future__ import annotations

import logging

from celery import shared_task

logger = logging.getLogger(__name__)


@shared_task(name="hotels.run_publication")
def run_publication(job_id: str) -> dict:
    from apps.hotels.services.platform import publication

    counts = publication.run(job_id)
    logger.info("публикация %s завершена: %s", job_id, counts)
    return counts

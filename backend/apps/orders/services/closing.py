"""
КОГДА ЗАКАЗ ЗАКРЫЛСЯ — ОДИН ОТВЕТ НА ВСЕХ.

До этой партии ответов было два, и оба читали журнал переходов:

  сводка смены — ПЕРВОЕ попадание в терминальный статус;
  аналитика    — ПОСЛЕДНЕЕ.

Пока терминальный статус был стеной, разницы не существовало физически: второго
терминального события у заказа взяться было неоткуда, и на стенде из 857
выполненных заказов ни один не имел двух. Разрешив возврат в работу, мы эту
разницу СОЗДАЛИ БЫ: заказ, закрытый в 14:00, возвращённый и закрытый снова в
19:00, попал бы в дневную сводку по 14:00, а в аналитику — по 19:00. Два экрана
про одну смену показали бы разные числа, и спорить было бы не о чем — оба
«правы» по своей формуле.

Теперь момент закрытия ХРАНИТСЯ полем `closed_at`, и обе стороны спрашивают
его здесь. Возврат в работу стирает поле, новое закрытие ставит заново — то
есть смена отчитывается за работу, которую в ней сделали.

ЖУРНАЛ ОСТАЁТСЯ ЗАПАСНЫМ ОТВЕТОМ, и только для заказов, закрытых до появления
поля: на стенде 821 такой заказ, им момент закрытия проставить неоткуда —
статус им выставила команда обслуживания напрямую, минуя журнал. Для них ответ
как был, так и остаётся пустым; убирать запасной путь нельзя, иначе заказы,
закрытые ДО миграции обычным образом, потеряли бы своё время.
"""

from __future__ import annotations

from datetime import datetime

from apps.orders.models import Order, OrderStatusChange


def closing_moments(orders) -> dict:
    """Момент закрытия для многих заказов разом — `{order_id: момент}`."""
    orders = list(orders)
    if not orders:
        return {}

    moments = {order.pk: order.closed_at for order in orders if order.closed_at}
    legacy = [order.pk for order in orders if not order.closed_at]
    if legacy:
        rows = (
            OrderStatusChange.objects.filter(
                order_id__in=legacy, to_status__is_terminal=True
            )
            .order_by("created_at")
            .values_list("order_id", "created_at")
        )
        # Первое попадание в терминал: у старых заказов их и не могло быть два.
        for order_id, moment in rows:
            moments.setdefault(order_id, moment)
    return moments


def closing_moment(order: Order) -> datetime | None:
    """Момент закрытия одного заказа; `None` — если он не закрыт или неизвестен."""
    return closing_moments([order]).get(order.pk)

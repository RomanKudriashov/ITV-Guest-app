"""
ЦИФРЫ ПО ТЕКУЩЕЙ ВЫБОРКЕ.

Сводка смены (`tracker_shift`) отвечает на вопрос «как идёт СЕГОДНЯШНЯЯ смена»
и считается с полуночи суток отеля. Это правильный ответ над активной доской и
неверный — над списком, который человек только что сузил фильтром: там он
смотрит на СВОЮ выборку, а плитка показывала бы соседнее множество.

Замер, из-за которого это заводится: после снятия окна в истории кухни 986
заказов, а плитка «Сделано» показывала 28 — столько закрыто за сегодня. Два
числа на одном экране, оба верные, и ни одно не про то, что видно в списке.

МЕДИАНА, А НЕ СРЕДНЕЕ — по той же причине, что и в сводке смены: один забытый
заказ, провисевший двое суток, утаскивает среднее в часы, и смена справедливо
перестаёт верить цифре.

Считается ОДНИМ проходом по тем же строкам, что и список: второй запрос с
другими условиями однажды разошёлся бы с первым.
"""

from __future__ import annotations

from statistics import median
from typing import Any


def selection_summary(queryset) -> dict[str, Any]:
    """
    Сводка по выборке: сколько заказов, на какую сумму, сколько отменено,
    типичная скорость.

    `queryset` — ТОТ ЖЕ, по которому строится список, до листания. Именно
    поэтому сюда передаётся запрос, а не список страницы: цифры обязаны быть
    про всю выборку, иначе «заказов 50» на первой странице из тысячи.
    """
    rows = list(
        queryset.values_list(
            "pk", "total", "created_at", "closed_at", "status__is_cancelled"
        )
    )

    total_minor = 0
    cancelled = 0
    durations: list[int] = []
    for _pk, total, created_at, closed_at, is_cancelled in rows:
        if is_cancelled:
            cancelled += 1
            # Отменённый заказ не приносит денег и не меряет скорость работы:
            # включить его в среднее значило бы хвалить смену за отказы.
            continue
        total_minor += int(total or 0)
        if closed_at is not None:
            durations.append(int((closed_at - created_at).total_seconds() // 60))

    return {
        "orders": len(rows),
        "revenue_minor": total_minor,
        "cancelled": cancelled,
        # None, а не ноль: «никто ещё ничего не закрыл» и «закрывают мгновенно»
        # — разные новости, и ноль сказал бы вторую вместо первой.
        "median_minutes": int(median(durations)) if durations else None,
    }

"""
Имя тестового бакета и его снос — ОДНО МЕСТО НА ФИКСТУРУ И НА ПРОВЕРКУ.

ЗАЧЕМ ПРИЗНАК ПРОГОНА. Раньше бакет назывался `guest-media-test-<воркер>` —
признака сессии в имени не было. Два одновременных прогона (полный набор и
точечный файл рядом) получали ОДИНАКОВЫЕ имена, а фикстура на выходе сносит
бакет вместе с содержимым. Значит завершение — в том числе аварийное — второй
сессии выдёргивало хранилище из-под первой, ещё работающей.

Выглядело это как десятки `NoSuchBucket` в тестах медиа, хранилища и сида
GRMS, то есть как поломка кода, которого никто не трогал. Один такой разбор
стоил около часа и закончился неверным выводом «это свойство набора».

ОТКУДА БЕРЁТСЯ ПРИЗНАК — И ПОЧЕМУ НЕ ИЗ ОКРУЖЕНИЯ. Сначала я поставил его
через `os.environ.setdefault`, рассчитывая, что воркеры унаследуют значение
контроллера. Проверка показала обратное: у четырёх воркеров вышло четыре
разных признака — контроллер не импортирует этот модуль до того, как поднимет
воркеров, и наследовать им нечего.

Изоляция при этом не пострадала (бакеты стали ещё более раздельными), но
обещание в комментарии разошлось с делом, а это здесь дороже.

Признак передаётся штатным способом xdist: контроллер кладёт его в
`workerinput` хуком `pytest_configure_node` (см. conftest), воркер читает
оттуда. Тогда все бакеты одного прогона действительно несут один признак и
стоят в листинге группой — а брошенные после аварии видно целой сессией.

ЕСЛИ `workerinput` НЕДОСТУПЕН (прогон без xdist, `-n 0`), берётся `RUN_ID`
этого процесса. Отказ падает в безопасную сторону: бакеты остаются
раздельными, каждый убирает за собой свой.

Файл назван `_bucket.py`, а не `test_*.py`: `python_files = test_*.py`, поэтому
сборщик его не подберёт, а импортировать из фикстуры и из проверки можно.
"""

from __future__ import annotations

import os
import uuid

#: Признак прогона. Ставится один раз в контроллере, наследуется воркерами.
RUN_ID = os.environ.setdefault("ITV_TEST_RUN", uuid.uuid4().hex[:8])


def bucket_for(base: str, worker_id: str, run_id: str | None = None) -> str:
    """
    `guest-media` + `gw0` → `guest-media-test-1a2b3c4d-gw0`.

    `run_id` параметром — чтобы проверка могла назвать два РАЗНЫХ прогона, не
    подменяя окружение и не перезагружая модуль. Подмена окружения в тесте
    оставляет след на соседях, а перезагрузка модуля меняет `RUN_ID` под уже
    поднятой фикстурой — то есть чинит проверку и ломает прогон.

    Порядок частей осознанный: признак прогона перед воркером. Так все бакеты
    одной сессии стоят в листинге рядом, и брошенные после аварии видно
    группой, а не вперемешку с чужими.
    """
    return f"{base}-test-{run_id or RUN_ID}-{worker_id}"


def drop_bucket(client, bucket: str) -> None:
    """
    Снести НАЗВАННЫЙ бакет вместе с содержимым.

    Объекты удаляются клиентом напрямую, а не через `storage.delete_objects`:
    тот работает по текущему `settings.MINIO_BUCKET`, и в помощнике, который
    принимает имя параметром, это была бы ловушка — снести можно было бы совсем
    не то, что попросили. В прежней фикстуре это сходило с рук лишь потому, что
    два имени там всегда совпадали.

    Пустой бакет удалить можно, непустой — нет, поэтому сначала объекты.
    """
    for item in client.list_objects(bucket, recursive=True):
        client.remove_object(bucket, item.object_name)
    client.remove_bucket(bucket)

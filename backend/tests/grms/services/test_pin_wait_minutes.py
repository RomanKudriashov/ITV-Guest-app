"""
Сколько минут ждать после блокировки PIN — округление ВВЕРХ.

Вниз оно отправляло гостя пробовать раньше срока: при остатке 90 секунд
сообщение говорило «через 1 мин», гость ждал минуту и снова получал отказ.
Текст обещал то, чего не выполнял.

Проверяется ГРАНИЦА, потому что ошибка живёт ровно на ней: и вверх, и вниз
дают одно и то же на круглых минутах, и разница видна только на остатке.
"""

from __future__ import annotations

import pytest

from apps.grms.services.pin import minutes_to_wait


@pytest.mark.parametrize(
    ("seconds", "expected"),
    [
        (1, 1),      # секунда всё ещё «минута»: ноль минут ждать нельзя
        (59, 1),
        (60, 1),     # ровно минута — ровно минута, вверх ничего не приписывает
        (61, 2),     # секунда сверх — уже две: за одну минуту не пустит
        (90, 2),     # тот самый случай, ради которого правка
        (15 * 60, 15),
        (4 * 3600, 240),  # потолок блокировки
    ],
)
def test_wait_minutes_round_up(seconds, expected):
    assert minutes_to_wait(seconds) == expected


def test_never_promises_zero_minutes():
    """
    «Попробуйте через 0 мин» — бессмыслица, и раньше от неё спасал `max(1, …)`.
    Потолок делает заплатку ненужной, но обещание остаётся проверенным.
    """
    assert all(minutes_to_wait(seconds) >= 1 for seconds in range(1, 121))


def test_the_promise_is_keepable():
    """
    Главное свойство: обещанного ожидания ДОСТАТОЧНО.

    Сказали «N мин» — значит через N минут блокировка уже прошла. При
    округлении вниз это ломалось на каждом остатке, не кратном минуте.
    """
    for seconds in range(1, 3601):
        assert minutes_to_wait(seconds) * 60 >= seconds
